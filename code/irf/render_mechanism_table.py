#!/usr/bin/env python3
"""Generate the H-collateral transmission table from the audited T=640 report.

The table is a decomposition of accounting identities evaluated on two solved
joint paths, not a causal impulse decomposition and not a DSGE equilibrium
certificate. The source audit is code/irf/audit_financial_blocks.py.
"""
import argparse
import json
import math
from pathlib import Path

HERE=Path(__file__).resolve().parent
REPO=HERE.parents[1]
SOURCE=HERE/"output/financial_blocks_audit/REPORT.json"
OUTPUT=REPO/"paper/irf_mechanism_table.tex"

def make_table(source):
    if source.get("status")!="passed_scoped_financial_block_audit":
        raise AssertionError("Financial audit has not passed")
    if source.get("full_equilibrium_validated") is not False:
        raise AssertionError("Unexpected scope flag: review the proof before publishing")
    data={s:source["branches"][s]["impact_H"] for s in ("slack","binding")}
    for branch,h in data.items():
        k=h["capital_identity_contributions"]
        b=h["credit_identity_contributions"]
        if abs(k["own_investible_resources"]+k["negative_effective_price"]-h["capital_next_log_pct"])>1e-10:
            raise AssertionError("Capital identity differs from T=640 audit")
        if abs(sum(b.values())-h["credit_log_pct"])>1e-10:
            raise AssertionError("Loan identity differs from T=640 audit")
        if not all(math.isfinite(v) for v in [
            *k.values(),*b.values(),h["capital_next_log_pct"],
            h["credit_log_pct"],h["normalized_multiplier_change"]]):
            raise AssertionError("Nonfinite impact")
    if not (data["slack"]["capital_next_log_pct"]>0>data["binding"]["capital_next_log_pct"]):
        raise AssertionError("Sign of capital response changed")
    specs=[
        (r"Recursos invertibles $100\Delta\log(N_H-c_H)$",
         lambda h:h["capital_identity_contributions"]["own_investible_resources"],8),
        (r"Menor precio efectivo $-100\Delta\log(q-H/R^L)$",
         lambda h:h["capital_identity_contributions"]["negative_effective_price"],8),
        (r"\textbf{Capital elegido} $100\Delta\log k_{H,t+1}$",
         lambda h:h["capital_next_log_pct"],8),
        (r"Valor pignorable $100\Delta\log H_H$",
         lambda h:h["credit_identity_contributions"]["pledge_value_per_capital"],8),
        (r"Menor tasa $-100\Delta\log R^L$",
         lambda h:h["credit_identity_contributions"]["negative_loan_rate"],8),
        (r"\textbf{Crédito} $100\Delta\log b_H$",
         lambda h:h["credit_log_pct"],8),
        (r"Dual normalizado $10^6\Delta\upsilon_H$",
         lambda h:1e6*h["normalized_multiplier_change"],5),
    ]
    lines=[
        r"% Generated by code/irf/render_mechanism_table.py; do not edit numeric cells by hand.",
        r"% T=640 nonlinear finite system, branch-specific reference; values are accounting log contributions.",
        r"\begin{tabular}{@{}lrr@{}}\toprule",
        r"Magnitud de impacto & Rama S & Rama B\\\midrule",
    ]
    for i,(title,key,digits) in enumerate(specs):
        if i in (3,6):
            lines.append(r"\addlinespace[2pt]")
        lines.append(title+" & "+f"{key(data['slack']):.{digits}f}"+" & "+
                     f"{key(data['binding']):.{digits}f}"+r"\\")
    lines.append(r"\bottomrule\end{tabular}")
    return "\n".join(lines)+"\n"

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--check",action="store_true",
                   help="fail if committed LaTeX differs from audited source")
    args=p.parse_args()
    content=make_table(json.loads(SOURCE.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8")!=content:
            raise SystemExit("Stale paper/irf_mechanism_table.tex; regenerate after financial audit")
        print("PASSED: mechanism table matches nonlinear financial audit (T=640)")
        return
    OUTPUT.write_text(content,encoding="utf-8")
    print("Generated paper/irf_mechanism_table.tex from financial audit T=640")

if __name__=="__main__":
    main()
