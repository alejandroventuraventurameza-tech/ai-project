"""Directed decimal enclosures for the history-tree inverse. No macro simulations."""
from pathlib import Path
from decimal import (Decimal as D, Context, ROUND_FLOOR, ROUND_CEILING,
                     ROUND_HALF_EVEN, getcontext)
from types import SimpleNamespace
import ast
import itertools
import json
import numpy as np

HERE = Path(__file__).parent
ROOT = HERE.parents[2]
PREC = 80
getcontext().prec = PREC + 20
DOWN = Context(prec=PREC, rounding=ROUND_FLOOR)
UP = Context(prec=PREC, rounding=ROUND_CEILING)
NEAR = Context(prec=PREC, rounding=ROUND_HALF_EVEN)

class I:
    """Closed real interval; endpoints never pass through a binary float."""
    __slots__ = ('lo', 'hi')
    def __init__(self, lo=0, hi=None):
        if isinstance(lo, I):
            self.lo, self.hi = lo.lo, lo.hi
            return
        if isinstance(lo, (float, np.floating)) or isinstance(hi, (float, np.floating)):
            raise TypeError('Use an explicit decimal string, not a float.')
        self.lo = D(str(lo))
        self.hi = self.lo if hi is None else D(str(hi))
        assert self.lo.is_finite() and self.hi.is_finite() and self.lo <= self.hi
    def __add__(self, other):
        if isinstance(other, np.ndarray): return NotImplemented
        b = I(other)
        return I(DOWN.add(self.lo,b.lo), UP.add(self.hi,b.hi))
    __radd__ = __add__
    def __neg__(self): return I(self.hi.copy_negate(), self.lo.copy_negate())
    def __sub__(self, other):
        if isinstance(other,np.ndarray):return NotImplemented
        return self + (-I(other))
    def __rsub__(self, other): return I(other) + (-self)
    def __mul__(self, other):
        if isinstance(other, np.ndarray): return NotImplemented
        b=I(other)
        return I(min(DOWN.multiply(x,y) for x in (self.lo,self.hi) for y in (b.lo,b.hi)),
                 max(UP.multiply(x,y) for x in (self.lo,self.hi) for y in (b.lo,b.hi)))
    __rmul__=__mul__
    def reciprocal(self):
        if self.lo <= 0 <= self.hi: raise ArithmeticError('Interval includes zero.')
        return I(DOWN.divide(D(1),self.hi),UP.divide(D(1),self.lo))
    def __truediv__(self,other):
        if isinstance(other,np.ndarray): return NotImplemented
        return self*I(other).reciprocal()
    def __rtruediv__(self,other): return I(other)*self.reciprocal()
    def __pow__(self,n):
        assert isinstance(n,int)
        if n<0: return (self**(-n)).reciprocal()
        if n==0: return I(1)
        if n==1: return self
        # Only multiplication is used, avoiding noninteger Context.power.
        a=self**(n//2)
        # Tight square enclosure, including intervals that cross zero.
        if a.lo>=0:
            square=I(DOWN.multiply(a.lo,a.lo),UP.multiply(a.hi,a.hi))
        elif a.hi<=0:
            square=I(DOWN.multiply(a.hi,a.hi),UP.multiply(a.lo,a.lo))
        else:
            square=I(0,max(UP.multiply(a.lo,a.lo),UP.multiply(a.hi,a.hi)))
        return square if n%2==0 else square*self
    def root(self,n):
        assert self.lo>=0 and n>=2
        def endpoint(x,lower):
            if x==0:return D(0)
            # A candidate is generated by ln/exp, but accepted only after
            # directed integer-power inequalities verify both endpoints.
            candidate=NEAR.exp(NEAR.divide(NEAR.ln(x),D(n)))
            lo,hi=DOWN.next_minus(candidate),UP.next_plus(candidate)
            count=0
            while (I(lo)**n).hi>x:
                lo=DOWN.next_minus(lo);count+=1
                if count>100:raise ArithmeticError('Root lower bracket failed.')
            while (I(hi)**n).lo<x:
                hi=UP.next_plus(hi);count+=1
                if count>100:raise ArithmeticError('Root upper bracket failed.')
            return lo if lower else hi
        return I(endpoint(self.lo,True),endpoint(self.hi,False))
    def exp(self):
        return I(DOWN.next_minus(NEAR.exp(self.lo)),UP.next_plus(NEAR.exp(self.hi)))
    def ln(self):
        assert self.lo>0
        return I(DOWN.next_minus(NEAR.ln(self.lo)),UP.next_plus(NEAR.ln(self.hi)))
    def magnitude(self): return max(self.lo.copy_abs(),self.hi.copy_abs())
    def midpoint(self): return (self.lo+self.hi)/2
    def __repr__(self):return f'I({self.lo},{self.hi})'

def arr(values): return np.array(values,dtype=object)
def zeros(shape):return np.full(shape,I(0),dtype=object)
def eye(n):return arr([[I(int(i==j)) for j in range(n)] for i in range(n)])
def point_matrix(x,digits=50):
    return arr([[I(format(v,f'.{digits}g')) for v in row] for row in x])
def midpoint(A):return arr([[x.midpoint() for x in row] for row in A])
def upper_norm(A):
    if A.ndim==1:return max(x.magnitude() for x in A)
    return max(sum_up(x.magnitude() for x in row) for row in A)
def sum_up(xs):
    out=D(0)
    for x in xs:out=UP.add(out,x)
    return out
def product_up(*xs):
    out=D(1)
    for x in xs:out=UP.multiply(out,x)
    return out
def quotient_up(a,b):return UP.divide(a,b)

def solve(A,B):
    """Point or interval Gauss-Jordan; excludes zero at every pivot."""
    A=A.copy();B=B.copy()
    vector=(B.ndim==1)
    if vector:B=B[:,None]
    n=A.shape[0]
    for k in range(n):
        row=max(range(k,n),key=lambda j: abs(float(A[j,k].midpoint() if isinstance(A[j,k],I) else A[j,k])))
        A[[k,row]]=A[[row,k]];B[[k,row]]=B[[row,k]]
        pivot=A[k,k]
        if isinstance(pivot,I):assert not pivot.lo<=0<=pivot.hi
        else:assert pivot!=0
        A[k,k:]=A[k,k:]/pivot;B[k]=B[k]/pivot
        for j in range(n):
            if j==k:continue
            factor=A[j,k]
            A[j,k:]=A[j,k:]-factor*A[k,k:]
            B[j]=B[j]-factor*B[k]
    return B[:,0] if vector else B

def steady():
    s=SimpleNamespace()
    for name,value in dict(bw='.99',be='.96',alpha='.4',beta='.5',delta='.025',
        phiI='.5',eps='6',sigmaE='1',sigmaW='1',varphi='1',chiW='1',
        rho='.1',zeta='.2',tight='.5',Delta='.02',eta='.1',aa='.5').items():
        setattr(s,name,I(value))
    s.ad=1-s.delta;s.gap=1-s.alpha-s.beta;s.gamma=s.alpha/(1-s.beta)
    s.mass=arr([I('.5'),I('.5')]);s.technology=arr([I('1.01'),I(1)])
    s.pledge=arr([I('.15'),I('.4')]);s.rd=1/s.bw
    s.vv=1/(1+I('1.5').root(2))
    s.cm=s.Delta*(1-s.aa+s.aa*s.vv);s.cp=s.Delta*s.tight*s.aa*s.vv
    s.cbar=(s.cm+s.cp)/2;s.cdiff=s.cm-s.cp
    AR=s.rd-(1-s.rho)*s.cbar-s.rho*s.zeta*s.cdiff/2
    s.rr=(AR+(AR*AR+2*s.rd*s.zeta*s.cdiff).root(2))/2
    s.rate=s.rr+s.cbar;s.xi=s.rd/s.rr
    s.h=s.rho+(s.xi-s.rho)*s.zeta*(1-s.tight)/(1+s.tight)
    s.ml=2*s.h;s.ll=3-s.ml;s.q=1+s.phiI*s.delta;s.mc=(s.eps-1)/s.eps
    s.uc=s.q*((1-s.pledge*s.ad/s.rate)/s.be-s.ad*(1-s.pledge))
    C=(1-s.beta)*(s.mc*s.technology)**2*s.beta
    kz=(s.gamma*C/s.uc)**5
    Kz=s.mass@kz;Yz=s.mass@(s.uc*kz/(s.alpha*s.mc));Lz=s.mass@(s.beta*s.uc*kz/s.alpha)
    Bz=s.mass@(s.pledge*s.ad*s.q*kz/s.rate)
    CWz=(1-(1-s.beta)*s.mc)*Yz+s.phiI*s.delta*s.delta*Kz/2+(s.rate-1)*Bz
    s.w=(s.chiW*Lz*CWz).root(12)
    s.k=kz*s.w**(-5)
    # Exact FOC identities avoid introducing numerical fractional powers.
    s.yy=s.uc*s.k/(s.alpha*s.mc);s.ell=s.beta*s.uc*s.k/(s.alpha*s.w)
    s.profit=(1-s.beta)*s.mc*s.yy;s.J=s.ad*s.q
    s.b=s.pledge*s.J*s.k/s.rate
    s.cc=s.profit-s.delta*s.q*s.k-(s.rate-1)*s.b
    s.K=s.mass@s.k;s.Y=s.mass@s.yy;s.L=s.mass@s.ell;s.B=s.mass@s.b
    s.CW=s.Y-s.mass@s.cc-(s.delta+s.phiI*s.delta*s.delta/2)*s.K
    s.E=s.B/s.ll;s.D=2*s.E;s.M=s.ml*s.E;s.aB=1/s.rate
    s.p=s.q-s.pledge*s.J/s.rate;s.F=s.pledge*s.J*s.k
    s.base=arr([*s.k,s.J,s.E,s.rr,s.M,*s.cc,s.CW,s.w,s.mc,I(1),s.q,s.rd,s.rate,s.tight])
    return s

def coefficients(s):
    old=HERE/'inputs/hand_linearization.py'
    tree=ast.parse(old.read_text(encoding='utf-8'))
    fn=next(n for n in tree.body if isinstance(n,ast.FunctionDef) and n.name=='coefficients')
    # Reuse the already audited hand stencil, with exact-decimal parameters
    # and interval matrix primitives. No old module execution or binary inputs.
    class MatrixAPI:
        eye=staticmethod(eye)
        zeros=staticmethod(lambda n:zeros((n,)))
        array=staticmethod(arr)
    ns=dict(vars(s));ns['np']=MatrixAPI
    ns['math']=SimpleNamespace(sqrt=lambda x:I(str(x)).root(2))
    exec(ast.unparse(fn),ns)
    return ns['coefficients'](phi_pi=I('1.5'),phi_y=I('.125'),rR=I('.5'),rM=I('.5'),phiP=I(150))[:2]

def refine_graph(C0,C1):
    old=np.load(HERE/'inputs/directional_coefficients.npz')
    P=midpoint(point_matrix(old['P'],17));P[:6]=midpoint(eye(6))
    F=midpoint(point_matrix(old['F'],17));A,B=midpoint(C0),midpoint(C1)
    Eu=midpoint(eye(16)[:,6:]);history=[]
    for _ in range(5):
        defect=A@P+B@P@F
        history.append(str(max(abs(x) for x in defect.flat)))
        inv=solve(np.column_stack((A@Eu,B@P)),midpoint(eye(16)))
        H,Jx=inv[:10],inv[10:]
        T=-H@B@Eu
        # Unknown dU has row-major order: dU - T*dU*F = -H*defect.
        operator=arr([[D(int(i==k and j==l))-T[i,k]*F[l,j]
                       for k in range(10) for l in range(6)]
                      for i in range(10) for j in range(6)])
        du=solve(operator,(-H@defect).reshape(60)).reshape(10,6)
        df=-Jx@defect-Jx@B@Eu@du@F
        P[6:]+=du;F+=df
    return point_matrix(P,55),point_matrix(F,55),history

def weighted_norm(A,left,right):return upper_norm(left@A@right)

def main():
    s=steady();C0,C1=coefficients(s)
    P0,F0,iterations=refine_graph(C0,C1)
    Eu=eye(16)[:,6:]
    K=zeros((16,));K[2:4]=s.be*s.pledge*s.J;K[4]=I(-1)
    a=zeros((16,));a[11]=a[12]=I(1)
    M=np.column_stack((C0@Eu,C1@P0));inv=solve(M,eye(16));H,Jx=inv[:10],inv[10:]
    T=-H@C1@Eu;V=-(H@K)[:,None]*(a@Eu)[None,:]
    old=np.load(HERE/'inputs/selected_coefficients.npz')
    R=point_matrix(old['R'],14);Ri=solve(R,eye(10))
    d=arr([I(format(v,'.7f')) for v in old['weight']])
    # Rv=R*diag(d) incorporates the weight in a simple infinity norm.
    Rv=R*d[None,:];Rvi=arr([[x/d[i] for x in row] for i,row in enumerate(Ri)])
    D0=(Rvi@(T-V)@Rv)*I('.75');D1=(Rvi@(T+3*V)@Rv)/4
    products=[eye(10)];norms=[D(1)]
    for n in range(1,9):
        products=[p@b for p in products for b in (D0,D1)]
        rows=[D(0)]*10
        for p in products:
            for i,row in enumerate(p):rows[i]=UP.add(rows[i],sum_up(x.magnitude() for x in row))
        norms.append(max(rows))
    q=norms[8];assert q<D(1)
    KB=quotient_up(sum_up(norms[:8]),DOWN.subtract(D(1),q))

    # A rational real eigenbasis is only a preconditioner, never asserted exact.
    ff=np.array([[float(x.midpoint()) for x in row] for row in F0])
    val,vec=np.linalg.eig(ff);columns=[]
    for j in range(6):
        if abs(val[j].imag)<1e-10:columns.append(vec[:,j].real)
        elif val[j].imag>0:columns.extend([vec[:,j].real,vec[:,j].imag])
    Rs=point_matrix(np.column_stack(columns),14);Rsi=solve(Rs,eye(6))
    Fs=Rsi@F0@Rs
    fp=eye(6);fnorm=[]
    for n in range(17):
        fnorm.append(upper_norm(fp));fp=fp@Fs
    qF=fnorm[16];assert qF<1
    KF=quotient_up(sum_up(fnorm[:16]),DOWN.subtract(D(1),qF))
    cF=max(fnorm[:16])
    defect=C0@P0+C1@P0@F0
    hv=upper_norm(Rvi@H@defect@Rs)
    jv=upper_norm(Rsi@Jx@defect@Rs)
    coupling=sum_up([upper_norm(Rsi@Jx@(C1-K[:,None]*a[None,:])@Eu@Rv),
                      upper_norm(Rsi@Jx@(K[:,None]*a[None,:])@Eu@Rv)])
    gamma=product_up(KF,sum_up([jv,product_up(coupling,KB,hv)]))
    assert gamma<D('1e-30')
    p_error=quotient_up(product_up(KB,hv,cF),DOWN.subtract(D(1),gamma))
    f_error=sum_up([jv,product_up(coupling,p_error)])
    f_feedback=product_up(KF,f_error)
    assert f_feedback<D('1e-30')
    KFstar=quotient_up(KF,DOWN.subtract(D(1),f_feedback))
    cFstar=quotient_up(cF,DOWN.subtract(D(1),f_feedback))
    f16star=sum_up([qF,product_up(D(16),*[UP.add(fnorm[1],f_error)]*15,f_error)])
    assert f16star<1
    # P* is the exact deterministic stable graph supplied by the corrected
    # bounded inverse. Its coordinate error is bounded by p_error.
    per_entry_error=product_up(upper_norm(Rv),p_error,upper_norm(Rsi))
    Ps=P0.copy()
    for i in range(6,16):
        for j in range(6):Ps[i,j]=Ps[i,j]+I(-per_entry_error,per_entry_error)
    Ms=np.column_stack((C0@Eu,C1@Ps))
    Finput=zeros((16,2));Finput[11,0]=I(-1);Finput[12,1]=I(-1)
    jR=1+s.rd*s.zeta*s.cdiff/(2*s.rr*s.rr)
    Finput[13,0]=-s.rr;Finput[14,0]=jR*s.rr
    Finput[15,0]=-s.D/s.h*s.xi*s.zeta*(1-s.tight)/(1+s.tight)
    Finput[15,1]=-(s.D-s.M)
    impact=solve(Ms,-Finput)
    Q=Eu@impact[:10];G=impact[10:]
    w=a@Q
    assert w[0].hi<0<w[1].lo
    gstar=2*w[1]
    boundary=eye(6)[2]-a@Ps
    assert boundary[2].lo>0

    # A valid full inverse bound from row-residual infinity norm to loglevels.
    Hb=upper_norm(Rvi@H);Jb=upper_norm(Rsi@Jx)
    Xgain=quotient_up(product_up(KF,sum_up([Jb,product_up(coupling,KB,Hb)])),DOWN.subtract(D(1),gamma))
    Vgain=product_up(KB,sum_up([Hb,product_up(hv,Xgain)]))
    Ygain=sum_up([product_up(upper_norm(P0@Rs),Xgain),product_up(upper_norm(Eu@Rv),Vgain)])
    # Exact affine first variation with initial x0=eta*(mean_shift[:6]).
    omega=-w[0]+w[1]
    shift=solve(C0+C1,K*omega)
    Mfirst=sum_up([upper_norm(shift),product_up(upper_norm(Ps@Rs),KFstar,upper_norm(Rsi@G)),upper_norm(Q)])
    WJ=product_up(upper_norm(Ps@Rs),cFstar,upper_norm(Rsi@eye(6)[:,2]))
    bJ=boundary[2].lo
    Caug=sum_up([Ygain,product_up(quotient_up(WJ,bJ),sum_up([D(1),2*Ygain]))])
    out={
        'scope':__doc__,'precision_decimal_digits':PREC,
        'primitive_parameters':'Exact decimal/rational values; no float conversion used for enclosure arithmetic.',
        'graph_refinement_residuals':iterations,
        'graph_defect_max_abs':str(upper_norm(defect)),
        'selected_eight_step_norm_upper':str(q),
        'backward_inverse_norm_upper':str(KB),
        'state_sixteen_step_norm_upper':str(qF),
        'stable_convolution_norm_upper':str(KF),
        'stable_initial_gain_upper':str(cF),
        'H_graph_defect_upper':str(hv),'J_graph_defect_upper':str(jv),
        'state_jump_coupling_upper':str(coupling),
        'graph_error_feedback_upper':str(gamma),
        'exact_graph_jump_coordinate_error_upper':str(p_error),
        'exact_graph_entry_error_upper':str(per_entry_error),
        'exact_transition_coordinate_error_upper':str(f_error),
        'exact_transition_sixteen_step_norm_upper':str(f16star),
        'exact_transition_convolution_norm_upper':str(KFstar),
        'price_shock_exposures':[[str(v.lo),str(v.hi)] for v in w],
        'worst_child_separation': [str(gstar.lo),str(gstar.hi)],
        'initial_contract_J_derivative':[str(boundary[2].lo),str(boundary[2].hi)],
        'full_inverse_residual_to_loglevel_norm_upper':str(Ygain),
        'state_inverse_gain_upper':str(Xgain),'jump_inverse_gain_upper':str(Vgain),
        'initial_J_homogeneous_plan_gain_upper':str(WJ),
        'augmented_inverse_including_initial_coverage_upper':str(Caug),
        'first_variation_plan_norm_upper':str(Mfirst),
        'risk_mean_shift_enclosures':[[str(v.lo),str(v.hi)] for v in shift],
        'limits':'Computer-assisted directed-decimal enclosure, not Lean/AML. Nonlinear Hessian and a quantitative shock radius are separate checks. No IRFs or time paths.',
    }
    HERE.joinpath('verified_linear_bounds.json').write_text(json.dumps(out, indent=2), encoding='utf-8', newline='\n')
    # Preserve all rational preconditioners and enclosed coefficients for replay.
    matrices={key:[[str(v.lo) for v in row] for row in A] for key,A in
              dict(P0=P0,F0=F0,Rv=Rv,Rs=Rs).items()}
    HERE.joinpath('rational_preconditioners.json').write_text(json.dumps(matrices, indent=2), encoding='utf-8', newline='\n')
    print(json.dumps(out,indent=2),flush=True)

if __name__=='__main__':main()
